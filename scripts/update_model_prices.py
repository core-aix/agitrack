#!/usr/bin/env python3
"""Regenerate ``agitrack/metrics/price_table.py``, the dashboard's dated price reference.

    python scripts/update_model_prices.py              # download https://models.dev/api.json
    python scripts/update_model_prices.py models.json  # or read a saved copy (OpenCode keeps
                                                        # one at ~/.cache/opencode/models.json)

models.dev lists every provider aGiTrack's backends use: the OpenAI models Codex uses,
the Anthropic models Claude uses and the providers OpenCode routes to; it is also OpenCode's
own catalog. Anthropic's first-party prices are written over its entries from ``ANTHROPIC``
below, checked against Anthropic's pricing page,
and the date the table was generated is recorded as the date it was added to aGiTrack, which
the dashboard shows beside every cost. Review the diff before committing it.
"""

from __future__ import annotations

import datetime as dt
import json
import sys
import urllib.request
from pathlib import Path

SOURCE = (
    "models.dev's published API prices for the OpenAI models Codex uses, the Anthropic models "
    "Claude uses and the other providers OpenCode reaches, with Anthropic's own price list for "
    "Claude models"
)

PROVIDERS = (
    "anthropic",
    "openai",
    "google",
    "deepseek",
    "opencode",
    "opencode-go",
    "xai",
    "mistral",
    "moonshotai",
    "zhipuai",
    "groq",
    "alibaba",
    "minimax",
    "openrouter",
)

# (input, output, cache read, 5-minute cache write), US dollars per million tokens.
ANTHROPIC = {
    "claude-fable-5-1": (10.0, 50.0, 0.25, 12.5),
    "claude-mythos-5-1": (10.0, 50.0, 0.25, 12.5),
    "claude-fable-5": (10.0, 50.0, 1.0, 12.5),
    "claude-mythos-5": (10.0, 50.0, 1.0, 12.5),
    "claude-opus-5-5": (4.0, 20.0, 0.2, 5.0),
    "claude-opus-5": (5.0, 25.0, 0.5, 6.25),
    "claude-opus-4-8": (5.0, 25.0, 0.5, 6.25),
    "claude-opus-4-7": (5.0, 25.0, 0.5, 6.25),
    "claude-opus-4-6": (5.0, 25.0, 0.5, 6.25),
    "claude-opus-4-5": (5.0, 25.0, 0.5, 6.25),
    "claude-opus-4-1": (15.0, 75.0, 1.5, 18.75),
    "claude-opus-4": (15.0, 75.0, 1.5, 18.75),
    "claude-sonnet-5-5": (2.0, 10.0, 0.2, 2.5),
    "claude-sonnet-5": (2.0, 10.0, 0.2, 2.5),
    "claude-sonnet-4-6": (3.0, 15.0, 0.3, 3.75),
    "claude-sonnet-4-5": (3.0, 15.0, 0.3, 3.75),
    "claude-sonnet-4": (3.0, 15.0, 0.3, 3.75),
    "claude-haiku-5-5": (0.1, 0.5, 0.01, 0.125),
    "claude-haiku-4-5": (1.0, 5.0, 0.1, 1.25),
    "claude-3-5-haiku": (0.8, 4.0, 0.08, 1.0),
}


def _num(cost: dict, key: str) -> float | None:
    value = cost.get(key)
    return round(float(value), 6) if isinstance(value, (int, float)) and not isinstance(value, bool) else None


def main() -> int:
    if len(sys.argv) > 1:
        catalog = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    else:
        request = urllib.request.Request("https://models.dev/api.json", headers={"User-Agent": "agitrack"})
        with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310
            catalog = json.loads(response.read())
    table: dict[str, dict[str, tuple]] = {}
    for provider in PROVIDERS:
        models = (catalog.get(provider) or {}).get("models") or {}
        rows = {}
        for name, model in sorted(models.items()):
            cost = model.get("cost") if isinstance(model, dict) else None
            if not isinstance(cost, dict):
                continue
            row = tuple(_num(cost, k) for k in ("input", "output", "cache_read", "cache_write", "reasoning"))
            if row[0] is None or row[1] is None or not (row[0] or row[1]):
                continue  # no per-token price, or "free": not something to quote
            rows[name] = row
        if rows:
            table[provider] = rows
    table.setdefault("anthropic", {}).update({name: (*rates, None) for name, rates in ANTHROPIC.items()})
    added = dt.date.today().isoformat()
    lines = [
        '"""Published per-token API prices: the dashboard\'s cost reference.',
        "",
        "GENERATED by scripts/update_model_prices.py; do not edit by hand, rerun it. Each row is",
        "(input, output, cache read, cache write, reasoning) in US dollars per million tokens;",
        "None means the source lists no separate rate (see metrics/pricing.py for the fallback).",
        '"""',
        "",
        f"SOURCE = {SOURCE!r}",
        f'ADDED = "{added}"',
        "",
        "PRICES: dict[str, dict[str, tuple[float | None, ...]]] = {",
    ]
    for provider, rows in table.items():
        lines.append(f"    {json.dumps(provider)}: {{")
        for name, row in sorted(rows.items()):
            lines.append(f"        {json.dumps(name)}: {row!r},")
        lines.append("    },")
    lines.append("}")
    out = Path(__file__).resolve().parent.parent / "agitrack" / "metrics" / "price_table.py"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({sum(len(r) for r in table.values())} models, added {added})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
